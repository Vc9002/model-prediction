"""Forward gate G2 report for nba-anchor-v10 (read-only; never touches models, ledgers or config).

  MODEL_PREDICTION_RUNTIME_ROOT=E:/model-prediction-runtime \\
  python scripts/nba_v10/g2_report.py [--as-of 2026-11-22T12:00:00Z] [--out-dir outputs/nba/v10_g2]

Writes ``G2_<ET date>.md`` and ``G2_<ET date>.json`` (same numbers) under ``--out-dir``. The scoring
rules, benchmark selection and verdict logic live in ``model_prediction.nba_v10_g2``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from model_prediction.cli.forecast_nba_anchor_v10 import ANCHOR_ARTIFACT, _load_verified
from model_prediction.domain import EASTERN, parse_utc, utc_now
from model_prediction.nba_v10_g2 import (
    BENCHMARK_LEAD,
    BENCHMARK_MAX_LEAD,
    BOOTSTRAP_DRAWS,
    G2_KILL_PICKS,
    G2_MIN_MEAN_CLV,
    G2_MIN_PICKS,
    run_g2,
)
from model_prediction.runtime_paths import RuntimePaths

REPO_ROOT = Path(__file__).resolve().parents[2]
RULES = {
    "tb": (
        "T-B rule (plan section 9; `main_min_edge` is null): a consensus-anchored row whose devigged "
        "consensus probability of a side minus the Polymarket ask for that side is >= 3.0 points, gross "
        "of fees, graded on that side. Rows anchored on the Polymarket mid are never G2 picks"
    ),
    "net_edge": "net-edge rule (`main_min_edge` is set): stored `net_edge` >= `main_min_edge` with a servable anchor",
}


def _rule_text(report: dict[str, Any]) -> str:
    return "; ".join(
        f"**{market}**: {RULES[rule]}" + ("" if rule == "tb" else f" ({report['main_min_edge'][market]})")
        for market, rule in report["g2_rule"].items()
    )


def _c(value: float | None, signed: bool = True) -> str:
    """Probability units as cents; never a sportsbook price."""
    if value is None:
        return "n/a"
    return f"{value * 100:+.2f}c" if signed else f"{value * 100:.1f}c"


def _ci(block: dict[str, Any]) -> str:
    if block["mean"] is None:
        return "n/a (no scored rows)"
    ci = "no CI (<2 games)" if block["low"] is None else f"95% CI [{_c(block['low'])}, {_c(block['high'])}]"
    return f"{_c(block['mean'])}, {ci}, n={block['n']} over {block['n_games']} games"


def _counts(counts: dict[str, int]) -> str:
    return ", ".join(f"{k} {v}" for k, v in counts.items()) or "none"


def _brier(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def render_markdown(report: dict[str, Any]) -> str:
    pops = report["populations"]
    g2 = pops["g2_picks"]
    lines = [
        f"# NBA v10 gate G2 -- {report['report_date_et']}",
        "",
        (
            f"As of {report['as_of_utc']}. Forward rows only: `nba-anchor-v10` Flat rows created at or after "
            f"{report['freeze_utc']} (wired 2026-11-21). Read-only; generated by `scripts/nba_v10/g2_report.py`."
        ),
        "",
        f"## Verdict: **{g2['verdict']}** ({g2['verdict_reason']})",
        "",
        f"- G2 pick rule per market: {_rule_text(report)}",
        (
            f"- Pre-registered: n >= {G2_MIN_PICKS}; mean consensus CLV >= {_c(G2_MIN_MEAN_CLV)} with the 95% "
            "game-cluster bootstrap CI above 0; mean paired CLV above v9's on the same game and market; Brier "
            f"no worse than the Polymarket decision mid. Any failure at >= {G2_KILL_PICKS} picks is KILL."
        ),
        "",
        "## Benchmark and decision time",
        "",
        (
            "- Decision time: v10 `model_input_snapshot_json.decision_time_utc`; v9 pair `created_at_utc`. "
            "Price paid: v10 snapshot `ask` (checked against the Polymarket decision quote at "
            "`market_slug` + `quote_observed_at_utc`); v9 the same decision quote's ask of its side."
        ),
        (
            f"- T-10 benchmark: the latest ESPN consensus capture (`odds/nba/<ET date>/espn_odds.jsonl`, "
            f"`observed_at_utc`) with decision_time < observed <= tip - {int(BENCHMARK_LEAD.total_seconds() // 60)} "
            "min, tip = the earlier of the row's and the capture's `event_start_utc`. Scored only after tip. "
            f"Captures older than tip - {int(BENCHMARK_MAX_LEAD.total_seconds() // 60)} min are `stale_benchmark` "
            "(excluded, counted)."
        ),
        (
            "- Consensus moved to the contract line with v10's normal translation and the row's sigma "
            f"(artifact: {report['sigma']}). CLV = consensus probability of the picked side minus the ask."
        ),
        (
            "- Polymarket-to-Polymarket CLV (settlement's closing ask after the decision, before tip, minus the "
            "ask) is shown for reference only, over every row with a close (no consensus benchmark needed). "
            "**It is NOT a G2 criterion**: v9 averages +0.58c on it while losing. C3 pairs are dropped when the "
            "v10 and v9 decisions are more than 15 min apart (different runs). C4 uses benchmark-scored picks."
        ),
        "",
        "## Scorecards",
        "",
        "| | " + " | ".join(name for name in pops) + " |",
        "|---|" + "---|" * len(pops),
    ]

    def row(label: str, fn) -> str:
        return f"| {label} | " + " | ".join(fn(p) for p in pops.values()) + " |"

    lines += [
        row("v10 rows", lambda p: str(p["rows"])),
        row("scored (benchmark found)", lambda p: str(p["scored"])),
        row("excluded", lambda p: _counts(p["excluded"])),
        row("C2 consensus CLV", lambda p: _ci(p["consensus_clv"])),
        row("C3 v10 minus v9 CLV (paired)", lambda p: _ci(p["v9_paired_clv_diff"])),
        row("C3 unpaired", lambda p: _counts(p["v9_paired_clv_diff"]["unpaired"])),
        row(
            "C4 Brier v10 / mid",
            lambda p: (
                f"{_brier(p['brier']['model'])} / {_brier(p['brier']['polymarket_mid'])} (n={p['brier']['n']})"
            ),
        ),
        row("C4 excluded", lambda p: _counts(p["brier"]["excluded"])),
        row("criteria", lambda p: ", ".join(f"{k} {v}" for k, v in p["criteria"].items())),
        row("would-be verdict", lambda p: p["verdict"]),
        row("Polymarket CLV (NOT G2)", lambda p: _ci(p["polymarket_clv_not_g2"])),
        row("benchmark lead (min)", lambda p: json.dumps(p["benchmark_lead_minutes"])),
        "",
        (
            "Only the g2_picks column carries the gate; all_flat and tb are informational. On rows anchored on the Polymarket mid the v10 "
            "probability IS the mid, so C4 ties there by construction; the split by anchor source:"
        ),
        "",
    ]
    for name, pop in pops.items():
        for source, block in pop["brier"]["by_anchor_source"].items():
            lines.append(
                f"- {name} / {source}: n={block['n']}, Brier v10 {_brier(block['brier_model'])}, "
                f"mid {_brier(block['brier_mid'])}"
            )
    lines += [
        "",
        "## Row accounting",
        "",
        f"- v10 rows dropped before scoring: {_counts(report['row_exclusions']['v10'])}",
        f"- v9 Flat rows on v10 games dropped: {_counts(report['row_exclusions']['v9'])}",
        f"- Load checks: {_counts(report['load_diagnostics']['rows'])}",
        f"- T-B evaluation on v10 rows: {_counts(report['load_diagnostics']['tb'])}",
        (
            f"- ESPN capture files read: {len(report['capture_files'])}; checks: "
            f"{_counts(report['capture_diagnostics'])}"
        ),
        "",
        "## v10 rows",
        "",
        (
            "| event | market | side | contract line | ask | decision (UTC) | tip (UTC) | benchmark observed | "
            "lead min | consensus | CLV | status |"
        ),
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in report["rows"]["all_flat"][:80]:
        lines.append(
            f"| {r['event_id']} | {r['market']} | {r['side']} | {r['contract_line']:g} | {_c(r['ask'], False)} | "
            f"{r['decision_time'][:19]} | {r['tip'][:16]} | {(r['benchmark_observed_at_utc'] or '')[:19]} | "
            f"{'' if r['benchmark_lead_minutes'] is None else r['benchmark_lead_minutes']} | "
            f"{_c(r['consensus_prob'], False)} | {_c(r['clv'])} | {r['reason'] or 'scored'} |"
        )
    if len(report["rows"]["all_flat"]) > 80:
        lines.append(f"\n({len(report['rows']['all_flat']) - 80} more rows in the JSON.)")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--as-of", help="UTC instant to score as of (default: now)")
    parser.add_argument("--out-dir", type=Path, default=REPO_ROOT / "outputs" / "nba" / "v10_g2")
    parser.add_argument("--draws", type=int, default=BOOTSTRAP_DRAWS)
    args = parser.parse_args(argv)

    paths = RuntimePaths.resolve(require_external_runtime=True)
    as_of = parse_utc(args.as_of) if args.as_of else utc_now()
    artifact = _load_verified(ANCHOR_ARTIFACT)
    report = run_g2(paths.ledgers_db, paths.data_root, artifact, as_of=as_of, draws=args.draws)
    report["report_date_et"] = as_of.astimezone(EASTERN).date().isoformat()
    report["artifact_hash"] = artifact["artifact_hash"]
    report["bootstrap_draws"] = args.draws
    report["sigma"] = {market: block.get("sigma") for market, block in artifact["markets"].items()}

    args.out_dir.mkdir(parents=True, exist_ok=True)
    stem = args.out_dir / f"G2_{report['report_date_et']}"
    stem.with_suffix(".json").write_text(
        json.dumps(report, indent=1, sort_keys=True) + "\n", encoding="utf-8"
    )
    stem.with_suffix(".md").write_text(render_markdown(report), encoding="utf-8")
    g2 = report["populations"]["g2_picks"]
    print(f"G2 {g2['verdict']}: {g2['verdict_reason']} -> {stem}.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
