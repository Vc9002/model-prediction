def resolve_team(name: str) -> CFBTeam | None:
    """Resolve a team string by canonical name or alias."""
    if not name:
        return None
    cleaned = name.strip()
    norm = cleaned.casefold()
    for team in CFB_TEAMS.values():
        if norm == team.canonical_name.casefold() or norm == team.abbreviation.casefold():
            return team
        for alias in team.aliases:
            if norm == alias.casefold():
                return team
    return None


resolve_cfb_team = resolve_team


def calculate_haversine_distance(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculate great-circle distance between two points in statute miles."""
    r_miles = 3958.8
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlam = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2.0) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlam / 2.0) ** 2
    c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))
    return r_miles * c


def calculate_timezone_difference(lon_origin: float, lon_dest: float) -> float:
    """Estimate standard timezone difference from longitude delta (15 deg / hr)."""
    d_deg = lon_dest - lon_origin
    return round(d_deg / 15.0, 1)


